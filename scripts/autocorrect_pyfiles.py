#!/usr/bin/env python3
"""
Autocorrect .py files:
- Replace common emoji glyphs with ASCII labels (WARNING: -> WARNING:, OK: -> OK:, ERROR: -> ERROR:, INFO: -> INFO:)
- For files under apps/tenant that declare `class X(models.Model)`, replace with `SintelTenantBaseModel` and add import if missing.
- Back up modified files as `filename.py.bak` before writing.

Use with caution; review changes in VCS before committing.
"""
import re
import sys
from pathlib import Path

ROOT = Path('.').resolve()
EMOJI_MAP = {
    'WARNING:': 'WARNING:',
    'OK:': 'OK:',
    'ERROR:': 'ERROR:',
    'INFO:': 'INFO:',
    '[LOCK]': '[LOCK]',
    '->': '->',
}

modified = []

for p in ROOT.rglob('*.py'):
    # skip virtualenv, migrations autogenerated and .py.bak files
    parts = set(p.parts)
    if 'venv' in parts or '.venv' in parts or 'node_modules' in parts:
        continue
    if p.name.endswith('.bak'):
        continue
    if 'migrations' in p.parts:
        continue

    try:
        text = p.read_text(encoding='utf-8')
    except Exception:
        # skip binary or unreadable
        continue
    orig = text

    # Replace emojis
    for k, v in EMOJI_MAP.items():
        if k in text:
            text = text.replace(k, v)

    # For tenant app files, attempt to replace models.Model inheritance
    path_str = str(p).replace('\\', '/')
    if path_str.startswith('apps/tenant/') or '/apps/tenant/' in path_str:
        # Replace class Xxx(models.Model):  -> class Xxx(SintelTenantBaseModel):
        new_text = re.sub(r'class\s+([A-Za-z0-9_]+)\s*\(\s*models\.Model\s*\)\s*:', r'class \1(SintelTenantBaseModel):', text)
        if new_text != text:
            text = new_text
            # add import if missing
            import_stmt = 'from apps.tenant.core.models import SintelTenantBaseModel'
            if import_stmt not in text:
                # Insert import after the first block of imports
                lines = text.splitlines()
                insert_at = 0
                for i, line in enumerate(lines):
                    if line.strip().startswith('from') or line.strip().startswith('import'):
                        insert_at = i + 1
                lines.insert(insert_at, import_stmt + '  # auto-inserted by autocorrect')
                text = '\n'.join(lines)

    if text != orig:
        bak = p.with_name(p.name + '.bak')
        if not bak.exists():
            bak.write_text(orig, encoding='utf-8')
        p.write_text(text, encoding='utf-8')
        modified.append(str(p))

if modified:
    print('Modified files:')
    for f in modified:
        print(' -', f)
    sys.exit(0)
else:
    print('No changes necessary')
    sys.exit(0)
